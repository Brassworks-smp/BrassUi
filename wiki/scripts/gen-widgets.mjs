const META_OUT = resolve(HERE, "../src/data/meta.ts");
const OWNER = "Brassworks-smp";
const REPO = "BrassUi";

function gradleProp(text, key) {
  const m = text.match(new RegExp(`^${key}=(.+)$`, "m"));
  return m ? m[1].trim() : "";
}

function writeMeta() {
  const props = readFileSync(GRADLE_PROPS, "utf8");
  const meta = {
    version: gradleProp(props, "version"),
    elementaVersion: gradleProp(props, "elementa_version"),
    universalcraftVersion: gradleProp(props, "universalcraft_version"),
    owner: OWNER,
    repo: REPO,
    repoUrl: `https://github.com/${OWNER}/${REPO}`,
    packagesUrl: "https://maven.opnsoc.org/releases",
  };
  writeFileSync(
    META_OUT,
    `// GENERATED by scripts/gen-widgets.mjs — do not edit by hand.\n` +
      `// Source: the build's gradle.properties. Re-run \`node scripts/gen-widgets.mjs\` to refresh.\n\n` +
      `export const META = ${JSON.stringify(meta, null, 2)} as const;\n`,
  );
  console.log(`Wrote meta: brassui ${meta.version}, elementa ${meta.elementaVersion}.`);
}
