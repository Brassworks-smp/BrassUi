// --- KDoc cleanup -------------------------------------------------------------------------------

/** Strip the comment framing off a raw `/** ... *\/` block, leaving the marked-down body. */
const kdocBody = (raw) =>
  raw
    .replace(/^\s*\/\*\*/, "")
    .replace(/\*\/\s*$/, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, ""))
    .join("\n");

/** Pull out ``` fenced blocks; returns { text: withoutFences, fences: [code, ...] }. */
function splitFences(body) {
  const fences = [];
  const text = body.replace(/```[a-zA-Z]*\n?([\s\S]*?)```/g, (_, code) => {
    fences.push(code.replace(/\s+$/, ""));
    return "";
  });
  return { text, fences };
}

/** Turn KDoc prose into plain, single-spaced text (drop tags, links, html). */
const proseOf = (text) =>
  text
    .replace(/<\/?p>/g, "\n\n")
    .replace(/<\/?h\d>/g, "\n\n")
    .replace(/^#{1,6}\s+.*$/gm, "") // drop KDoc `### Why ...` section headers - internal rationale
    .replace(/<\/?[a-z][^>]*>/gi, "")
    .replace(/\{@link\s+([^}]+)\}/g, (_, r) => r.split(/[.#]/).pop().trim())
    .replace(/\[([^\]]+)\]\[[^\]]+\]/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]/g, (_, r) => r.split(/[.#]/).pop().trim())
    .replace(/\s*-\s*/g, ", ") // the wiki carries no em dashes; fold them into a clause break
    .replace(/[ \t]+/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .trim();

/** First sentence (or first line) of the prose - the blurb we actually show. */
function firstSentence(prose) {
  const flat = prose.split(/\n\n/)[0].replace(/\s+/g, " ").trim();
  // Split on the first sentence end that isn't an abbreviation like "e.g." - good enough here.
  const m = flat.match(/^(.*?[.!?])(\s|$)/);
  let s = (m ? m[1] : flat).trim();
  if (s.length > 200) s = s.slice(0, 197).trimEnd() + "…";
  return s;
}

// --- constructor parameter parsing --------------------------------------------------------------

/**
 * Depth at each character, respecting () [] {} and generic <...>, strings, and - crucially - NOT
 * mistaking the `>` in a `->` arrow (or `>=`) for a closing angle bracket. `<` only opens a generic
 * when it follows a type-ish character, so a stray comparison never unbalances the scan.
 */
function bracketDepths(s) {
  const depth = new Array(s.length).fill(0);
  let round = 0;
  let angle = 0;
  let str = null;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (str) {
      depth[i] = round + angle;
      if (c === str && s[i - 1] !== "\\") str = null;
      continue;
    }
    if (c === '"' || c === "'") {
      str = c;
      depth[i] = round + angle;
      continue;
    }
    if (c === "(" || c === "[" || c === "{") {
      round++;
      depth[i] = round + angle;
    } else if (c === ")" || c === "]" || c === "}") {
      depth[i] = round + angle;
      round--;
    } else if (c === "<" && /[A-Za-z0-9_>?,\s]/.test(s[i - 1] || "")) {
      angle++;
      depth[i] = round + angle;
    } else if (c === ">" && s[i - 1] !== "-" && s[i + 1] !== "=" && angle > 0) {
      depth[i] = round + angle;
      angle--;
    } else {
      depth[i] = round + angle;
    }
  }
  return depth;
}

/** Split on top-level commas. */
function splitTopLevel(s) {
  const depth = bracketDepths(s);
  const out = [];
  let buf = "";
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "," && depth[i] === 0) {
      out.push(buf);
      buf = "";
    } else buf += s[i];
  }
  if (buf.trim()) out.push(buf);
  return out;
}

// Find the primary-constructor parameter list `( ... )` for `class NAME`, balanced. Per-param doc
// comments are kept (parseParam reads them), but the brackets inside any comment are neutralised so a
// bracketed aside or link in a doc can't swallow the scan.
function constructorParamText(rawSrc, name) {
  // Neutralise brackets inside comments without deleting the comment (parseParam still reads the doc).
  const src = rawSrc.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[()[\]{}<>]/g, " ")).replace(/\/\/[^\n]*/g, "");
  const start = src.search(new RegExp(`\\bclass\\s+${name}\\b`));
  if (start < 0) return null;
  // Walk from the class name to the first '(' that opens the ctor, but stop if a '{' (class body)
  // or top-level ':' (supertype list, no ctor) comes first. Skip a generic `<...>` right after name.
  let i = start + src.slice(start).match(new RegExp(`\\bclass\\s+${name}`))[0].length;
  // skip generics
  if (src[skipWs(src, i)] === "<") {
    let d = 0;
    i = skipWs(src, i);
    for (; i < src.length; i++) {
      if (src[i] === "<") d++;
      else if (src[i] === ">") {
        d--;
        if (d === 0) {
          i++;
          break;
        }
      }
    }
  }
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === "(") break;
    if (c === "{" || c === ":") return null; // body or supertype before any ctor parens
    if (c === "@") {
      // annotation / `constructor` keyword may sit before '(' - keep scanning
    }
  }
  if (src[i] !== "(") return null;
  let depth = 0;
  let j = i;
  for (; j < src.length; j++) {
    if (src[j] === "(") depth++;
    else if (src[j] === ")") {
      depth--;
      if (depth === 0) break;
    }
  }
  return src.slice(i + 1, j);
}

const skipWs = (s, i) => {
  while (i < s.length && /\s/.test(s[i])) i++;
  return i;
};

/**
 * The full declaration signature: modifiers, keyword, name, generics, the balanced primary
 * constructor, and the supertype list up to the class body. Comments stripped, blank runs collapsed,
 * em dashes gone - reads as a signature, not an essay.
 */
function fullSignature(rawSrc, name) {
  // Scan a comment-free copy so a stray bracket in KDoc prose can't unbalance the paren/brace count.
  const src = rawSrc.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
  const kw = src.search(new RegExp(`\\b(?:class|object|interface)\\s+${name}\\b`));
  if (kw < 0) return null;
  // Walk back over leading modifiers on the declaration.
  let start = kw;
  const before = src.slice(0, kw).replace(/\s+$/, "");
  const modMatch = before.match(/((?:\b(?:public|internal|private|protected|open|abstract|sealed|final|data|enum|annotation|value|inner|inline)\b\s+)+)$/);
  if (modMatch) start = kw - modMatch[1].length;
  // Find the end: balanced ctor `()` if present, then scan to the class body `{` at depth 0.
  let i = kw;
  let end = src.length;
  let round = 0;
  let angle = 0;
  let sawCtor = false;
  let str = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (str) {
      if (c === str && src[i - 1] !== "\\") str = null;
      continue;
    }
    if (c === '"' || c === "'") {
      str = c;
      continue;
    }
    if (c === "(") {
      round++;
      sawCtor = true;
    } else if (c === ")") round--;
    else if (c === "<" && /[A-Za-z0-9_>?,\s]/.test(src[i - 1] || "")) angle++;
    else if (c === ">" && src[i - 1] !== "-" && angle > 0) angle--;
    else if (c === "{" && round === 0 && angle === 0) {
      // A `{` at top level: either a `{}` default inside the ctor (round>0 handled) or the class body.
      end = i;
      break;
    }
  }
  let sig = src.slice(start, end);
  sig = sig
    .replace(/\/\*\*[\s\S]*?\*\//g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{2,}/g, "\n")
    .replace(/\s*-\s*/g, ", ")
    .trim();
  if (sig.length > 700) sig = sig.slice(0, 700).trimEnd() + "…";
  return sig || null;
  void sawCtor;
}

/** Parse one raw parameter chunk into { name, type, default?, doc? }. */
function parseParam(chunk) {
  let s = chunk;
  let doc;
  // leading /** ... */ note
  const dm = s.match(/^\s*\/\*\*([\s\S]*?)\*\//);
  if (dm) {
    doc = proseOf(kdocBody(`/**${dm[1]}*/`));
    doc = firstSentence(doc);
    s = s.slice(dm[0].length);
  }
  s = s.replace(/\/\/.*$/gm, "").trim();
  // strip leading annotations like @Foo or @Foo(...)
  while (/^@[\w.]+/.test(s)) {
    s = s.replace(/^@[\w.]+(\([^)]*\))?\s*/, "");
  }
  // strip modifiers
  s = s.replace(/^(?:override\s+|private\s+|internal\s+|protected\s+|public\s+|open\s+|final\s+|val\s+|var\s+|vararg\s+|crossinline\s+|noinline\s+)+/g, "");
  const colon = topLevelIndex(s, ":");
  if (colon < 0) return null;
  const name = s.slice(0, colon).trim();
  let rest = s.slice(colon + 1).trim();
  let def;
  const eq = topLevelIndex(rest, "=");
  if (eq >= 0) {
    def = rest.slice(eq + 1).trim();
    rest = rest.slice(0, eq).trim();
  }
  const type = rest.replace(/\s+/g, " ").trim();
  if (!name || !/^[A-Za-z_]\w*$/.test(name)) return null;
  return { name, type, ...(def ? { default: def } : {}), ...(doc ? { doc } : {}) };
}

/** Index of the first top-level occurrence of a single-char token (respecting brackets/strings). */
function topLevelIndex(s, token) {
  const depth = bracketDepths(s);
  for (let i = 0; i < s.length; i++) {
    if (s[i] === token && depth[i] === 0) {
      // don't treat "==", "=>", ">=", "<=", "->" '=' as a default marker
      if (
        token === "=" &&
        (s[i + 1] === "=" || s[i - 1] === "=" || s[i - 1] === "!" || s[i - 1] === "<" || s[i - 1] === ">")
      )
        continue;
      return i;
    }
  }
  return -1;
}

function parseParams(src, name) {
  const text = constructorParamText(src, name);
  if (text == null) return [];
  return splitTopLevel(text)
    .map(parseParam)
    .filter(Boolean);
}

// --- demo extraction ----------------------------------------------------------------------------

/** Extract { demoName, snippet } from a `override fun demo() = BrassDemo("id", ...) { body }`. */
function extractDemo(src) {
  const idx = src.indexOf("BrassDemo(");
  if (idx < 0) return {};
  const nameM = src.slice(idx).match(/BrassDemo\(\s*"([^"]+)"/);
  const demoName = nameM ? nameM[1] : undefined;
  // Grab the trailing lambda body: find the '{' that closes the BrassDemo(...) call args.
  let i = idx + "BrassDemo".length;
  // skip to end of the (...) argument list
  let depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === "(") depth++;
    else if (src[i] === ")") {
      depth--;
      if (depth === 0) {
        i++;
        break;
      }
    }
  }
  i = skipWs(src, i);
  let snippet;
  if (src[i] === "{") {
    let d = 0;
    const start = i;
    for (; i < src.length; i++) {
      if (src[i] === "{") d++;
      else if (src[i] === "}") {
        d--;
        if (d === 0) {
          i++;
          break;
        }
      }
    }
    const body = src.slice(start + 1, i - 1);
    snippet = dedent(body).trim();
    if (snippet.length > 400 || !snippet) snippet = undefined;
  }
  return { demoName, snippet };
}

/** Remove common leading indentation from a block. */
function dedent(s) {
  const lines = s.replace(/^\n+/, "").replace(/\s+$/, "").split("\n");
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^\s*/)[0].length);
  const min = indents.length ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(min)).join("\n");
}

