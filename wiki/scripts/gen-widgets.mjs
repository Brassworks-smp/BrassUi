const entries = [];
for (const cat of CATEGORIES) {
  const dir = join(CORE, cat.dir);
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".kt"))) {
    const name = basename(f, ".kt");
    const src = readFileSync(join(dir, f), "utf8");

    const re = new RegExp(
      `(/\\*\\*[\\s\\S]*?\\*/)\\s*(?:@[\\w.]+(?:\\([^)]*\\))?\\s*)*(?:public |internal |open |abstract |sealed |final |data |enum )*(class|object|interface|enum class)\\s+${name}\\b`,
    );
    const m = src.match(re);
    let kind = "class";
    let fences = [];
    let summary = "";
    if (m) {
      kind = m[2].includes("object") ? "object" : m[2].includes("interface") ? "interface" : "class";
      const split = splitFences(kdocBody(m[1]));
      fences = split.fences;
      summary = firstSentence(proseOf(split.text));
    }

    // Declaration signature: class/object keyword up to the opening brace or supertype list.
    let signature = fullSignature(src, name) ?? `${kind} ${name}`;

    const params = kind === "class" ? parseParams(src, name) : [];
    const { demoName, snippet } = extractDemo(src);

    // Usage examples: KDoc fences first (curated), then the demo builder body (real construction).
    const examples = [...fences];
    if (snippet && !examples.some((e) => e.includes(snippet.split("\n")[0].trim()))) {
      examples.push(snippet);
    }

    entries.push({
      name,
      kind,
      category: cat.label,
      categoryDir: cat.dir,
      slug: name,
      summary,
      params,
      examples,
      signature,
      ...(demoName ? { demoName } : {}),
    });
  }
}

entries.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));

const out = `// GENERATED by scripts/gen-widgets.mjs - do not edit by hand.
// Source: brassui core Kotlin sources. Re-run \`node scripts/gen-widgets.mjs\` to refresh.

export type Param = {
  name: string;
  type: string;
  default?: string;
  doc?: string;
};

export type Widget = {
  name: string;
  kind: "class" | "object" | "interface";
  category: string;
  categoryDir: string;
  slug: string;
  summary: string;
  params: Param[];
  examples: string[];
  signature: string;
  demoName?: string;
};

export const CATEGORIES = ${JSON.stringify(CATEGORIES.map(({ dir, label, blurb }) => ({ dir, label, blurb })), null, 2)} as const;

export const WIDGETS: Widget[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT, out);
const withEx = entries.filter((e) => e.examples.length).length;
const withParams = entries.filter((e) => e.params.length).length;
console.log(`Wrote ${entries.length} widgets - ${withParams} with params, ${withEx} with examples.`);

writeMeta();
